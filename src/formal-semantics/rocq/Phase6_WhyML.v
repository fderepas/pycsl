(* Phase6_WhyML.v — WhyML Subset AST
   Defines the 13-constructor WhyML subset generated by Module 6.
   "Module 6" = `src/pycsl/Module6_WhyMLTranspiler.py` (facade) +
   `src/pycsl/module6_whyml/` (10 emission mixins, post-refactor).
   The key design decision: runtime expression positions use `expr`, while
   spec positions (invariants, variants, assertions, ghost values) use
   `contract_expr`. This mirrors Module 6's output structure exactly and
   makes `gen` (Phase6d_StmtGen) a near-identity function requiring no
   expression translation. *)

Require Import ZArith String.
Require Import Phase1_AST.
Open Scope string_scope.

(* Exception name type: the four exception flavours Module6 generates *)
Inductive whyml_exc : Type :=
  | ExcReturn               (* SReturn e  → WSeq (WAssign "\result" e) (WRaise ExcReturn) *)
  | ExcBreak                (* SBreak     → WRaise ExcBreak *)
  | ExcContinue             (* SContinue  → WRaise ExcContinue *)
  | ExcNamed (name : ident) (* SRaise exc → WRaise (ExcNamed exc) *).

(* WhyML statement AST — exactly the constructs Module6 can emit.
   Runtime expressions (eval_bool / eval_expr) keep type `expr`.
   Spec expressions (eval_c / eval_v) keep type `contract_expr = ghost_expr`. *)
Inductive whyml_stmt : Type :=
  | WSkip
  (* runtime assignment *)
  | WAssign    (x : ident)   (e : expr)
  | WAugAssign (x : ident)   (op : binop)    (e : expr)
  | WArraySet  (arr : ident) (i : expr)      (v : expr)
  (* control flow *)
  | WSeq       (w1 w2 : whyml_stmt)
  | WIf        (cond : expr) (w_then w_else : whyml_stmt)
  | WWhile     (inv : contract_expr) (var : contract_expr)
               (cond : expr)  (body : whyml_stmt)
  (* exception-encoded control flow *)
  | WRaise     (exc : whyml_exc)
  | WTryCatch  (body : whyml_stmt) (exc : ident) (handler : whyml_stmt)
  (* ghost statements — use ghost_expr = contract_expr *)
  | WGhostDecl   (x : ident) (t : ghost_type) (e : ghost_expr)
  | WGhostAssign (x : ident) (t : ghost_type) (op : aug_op) (e : ghost_expr)
  | WLabel     (L : ident)
  (* assertion — spec-level condition *)
  | WAssert    (cond : contract_expr) (msg : string).
